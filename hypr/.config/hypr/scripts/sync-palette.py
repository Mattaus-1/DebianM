#!/usr/bin/env python3
import json
from pathlib import Path
import shutil
import subprocess

home = Path.home()
palette = json.loads((home / '.cache/wal/colors.json').read_text())
colors = palette['colors']

# pywal 3 does not ship a Waybar template on every distribution.
# Use the palette exactly as extracted from the wallpaper.
css = '\n'.join(f'@define-color {k} {v};' for k, v in {**palette['special'], **colors}.items())
(home / '.cache/wal/colors-waybar.css').write_text(css + '\n')
accent = colors['color4'].lstrip('#')
subprocess.run(['hyprctl', 'eval', f"hl.config({{general={{col={{active_border='rgb({accent})'}}}}}})"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def cava_color_block(colors):
    return (
        '# Generated by sync-palette.py - follows the desktop (pywal) palette.\n'
        '# Edit sync-palette.py instead of this block, changes here are overwritten.\n'
        '[color]\n'
        '# Background stays the terminal/wallpaper color (gradients need a non-hex bg).\n'
        '; background = default\n'
        'gradient = 1\n'
        'gradient_count = 3\n'
        f"gradient_color_1 = '{colors['color1']}'\n"
        f"gradient_color_2 = '{colors['color4']}'\n"
        f"gradient_color_3 = '{colors['color7']}'\n"
    )


# Dashboard visualizer gets its own small config.
cava = home / '.config/cava/iridescent.conf'
cava.write_text(
    '[general]\nframerate = 60\nbars = 20\n[output]\nmethod = noncurses\n'
    + cava_color_block(colors)
)

# Keep the interactive fish prompt on the same accent as the rest of the desktop.
# Universal variables update every open fish session, not just new ones.
if shutil.which('fish'):
    fish_colors = {
        'fish_color_user': [colors['color4']],
        'fish_color_host': [colors['color9']],
        'fish_color_host_remote': [colors['color9']],
        'fish_color_cwd': [colors['color4']],
        'fish_color_cwd_root': [colors['color9']],
        'fish_color_param': [colors['color9']],
        'fish_color_operator': [colors['color9']],
        'fish_color_escape': [colors['color9']],
        'fish_color_redirection': [colors['color9'], '--bold'],
        'fish_color_autosuggestion': [colors['color8']],
        'fish_color_selection': [palette['special']['background'], f"--background={colors['color4']}"],
    }
    script = '; '.join(
        f"set -U {name} " + ' '.join(f"'{value}'" for value in values)
        for name, values in fish_colors.items()
    )
    subprocess.run(['fish', '-c', script], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
